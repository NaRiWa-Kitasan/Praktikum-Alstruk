#Buat variabel berikut, tampilkan nilainya dan tipe datanya menggunakan type().
nama = "Fajar" 
umur = 19 
berat = 54.5 
terdaftar = True 
#1. Tampilkan semua nilai variabel.
print(nama,umur,berat,terdaftar)
#2. Tampilkan tipe data setiap variabel.
print(type(nama),type(umur),type(berat),type(terdaftar))
#3. Ubah nilai umur menjadi 20. Apa yang berubah pada output?
